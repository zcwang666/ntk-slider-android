/**
 * 发布签名：若仓库根目录存在 keystore.properties 就用正式密钥，
 * 否则回退到调试签名（方便他人直接 clone 后构建）。
 */
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}
val hasReleaseKeystore = keystorePropertiesFile.exists()

android {
    namespace = "com.nuotaike.ntk1"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.nuotaike.ntk1"
        minSdk = 26
        targetSdk = 35
        versionCode = 10
        versionName = "1.10.0"
    }

    signingConfigs {
        if (hasReleaseKeystore) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            isMinifyEnabled = false
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
            signingConfig = if (hasReleaseKeystore) {
                signingConfigs.getByName("release")
            } else {
                signingConfigs.getByName("debug")
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        compose = true
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }

    testOptions {
        unitTests {
            isReturnDefaultValues = true
            isIncludeAndroidResources = true
        }
    }
}

/**
 * Robolectric 需要在 HOME 下缓存 android-all 运行时。
 * 受限环境（如只读 HOME）会导致它下载失败，这里统一切到模块下的 .robolectric 目录。
 * 注意：不能放在 build/ 里——clean 会把它删掉，导致测试启动时连锁文件都建不出来。
 */
tasks.withType<Test>().configureEach {
    val roboHome = layout.projectDirectory.dir(".robolectric").asFile
    systemProperty("user.home", roboHome.absolutePath)
    systemProperty("maven.repo.local", roboHome.resolve(".m2/repository").absolutePath)
    doFirst { roboHome.mkdirs() }
    maxHeapSize = "2048m"
}

